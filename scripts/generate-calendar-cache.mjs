#!/usr/bin/env node

/**
 * Generate calendar cache SQL for PostgreSQL/Supabase.
 *
 * Requirements:
 * - DATA_GO_KR_SERVICE_KEY: service key issued by data.go.kr, or --key-file temp.txt.
 *
 * Usage:
 *   DATA_GO_KR_SERVICE_KEY="..." node scripts/generate-calendar-cache.mjs --from 1900 --to 2100 --out db/calendar-cache.sql
 *   node scripts/generate-calendar-cache.mjs --key-file temp.txt --from 1900 --to 2100 --out db/calendar-cache.sql
 *
 * Notes:
 * - This script intentionally runs outside GitHub Pages.
 * - GitHub Pages cannot call this securely because the API key would be public.
 * - The generated SQL fills calendar_days and solar_terms.
 */

import fs from "node:fs/promises";

const args = parseArgs(process.argv.slice(2));
const fromYear = Number(args.from || 1900);
const toYear = Number(args.to || 2100);
const outPath = args.out || "db/calendar-cache.sql";
const skipSolarTerms = Boolean(args["skip-solar-terms"]);
const onlySolarTerms = Boolean(args["only-solar-terms"]);
const serviceKey = await readServiceKey();

if (!serviceKey) {
  console.error("Missing service key. Set DATA_GO_KR_SERVICE_KEY or pass --key-file temp.txt.");
  process.exit(1);
}

const lunarBaseUrl = "http://apis.data.go.kr/B090041/openapi/service/LrsrCldInfoService";
const specialBaseUrl = "http://apis.data.go.kr/B090041/openapi/service/SpcdeInfoService";

const sql = [];
sql.push("-- Generated calendar cache. Do not edit by hand.");
sql.push("-- Source: KASI public data APIs via data.go.kr.");
sql.push("BEGIN;");
sql.push(`
INSERT INTO data_sources (id, name, url, license, retrieved_at, source_version, notes)
VALUES
  ('kasi-calendar-api', 'Korea Astronomy and Space Science Institute calendar APIs', 'https://www.data.go.kr/', 'Public data usage terms apply', now(), '${escapeSql(`${fromYear}-${toYear}`)}', 'Generated by scripts/generate-calendar-cache.mjs')
ON CONFLICT (id) DO UPDATE SET
  retrieved_at = now(),
  source_version = EXCLUDED.source_version,
  notes = EXCLUDED.notes,
  updated_at = now();
`);

for (let year = fromYear; year <= toYear; year += 1) {
  if (!onlySolarTerms) {
    console.log(`Fetching ${year} calendar data...`);
    const days = await fetchSolarYear(year);
    if (days.length === 0) {
      console.warn(`No calendar data returned for ${year}. Check API supported range.`);
    }
    for (const day of days) {
      sql.push(calendarDaySql(day));
    }
  }

  if (!skipSolarTerms) {
    console.log(`Fetching ${year} solar terms...`);
    const terms = await fetchSolarTerms(year);
    for (const term of terms) {
      sql.push(solarTermSql(term, year));
    }
  }
}

sql.push("COMMIT;");
await fs.writeFile(outPath, `${sql.join("\n")}\n`, "utf8");
console.log(`Wrote ${outPath}`);

async function fetchSolarYear(year) {
  const rows = [];
  for (let month = 1; month <= 12; month += 1) {
    const url = new URL(`${lunarBaseUrl}/getLunCalInfo`);
    url.searchParams.set("ServiceKey", serviceKey);
    url.searchParams.set("solYear", String(year));
    url.searchParams.set("solMonth", String(month).padStart(2, "0"));
    url.searchParams.set("numOfRows", "40");
    url.searchParams.set("pageNo", "1");

    const data = await fetchJson(url);
    rows.push(...normalizeItems(data));
  }
  return rows;
}

async function fetchSolarTerms(year) {
  const url = new URL(`${specialBaseUrl}/get24DivisionsInfo`);
  url.searchParams.set("ServiceKey", serviceKey);
  url.searchParams.set("solYear", String(year));
  url.searchParams.set("numOfRows", "30");
  url.searchParams.set("pageNo", "1");

  const data = await fetchJson(url);
  return normalizeItems(data);
}

async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${redactServiceKey(url)}`);
  }
  const text = await response.text();
  if (text.includes("<resultCode>") && !text.includes("<resultCode>00</resultCode>")) {
    throw new Error(`API error from ${redactServiceKey(url)}: ${text.slice(0, 300)}`);
  }
  return parseXmlItems(text);
}

function parseXmlItems(xml) {
  const matches = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)];
  return matches.map((match) => {
    const itemXml = match[1];
    const item = {};
    for (const field of [...itemXml.matchAll(/<([^/][^>]*)>([\s\S]*?)<\/\1>/g)]) {
      item[field[1]] = decodeXml(field[2]);
    }
    return item;
  });
}

function normalizeItems(data) {
  return data;
}

function calendarDaySql(row) {
  const date = `${row.solYear}-${pad(row.solMonth)}-${pad(row.solDay)}`;
  const isLeapMonth = String(row.lunLeapmonth || row.lunLeapMonth || "").trim() === "윤";
  const weekday = weekdayNumber(date);

  return `
INSERT INTO calendar_days
  (date, solar_year, solar_month, solar_day, lunar_year, lunar_month, lunar_day, is_leap_month, year_ganji, month_ganji, day_ganji, julian_day, weekday, source_id, source_version)
VALUES
  ('${date}', ${num(row.solYear)}, ${num(row.solMonth)}, ${num(row.solDay)}, ${num(row.lunYear)}, ${num(row.lunMonth)}, ${num(row.lunDay)}, ${isLeapMonth}, '${escapeSql(row.lunSecha)}', '${escapeSql(row.lunWolgeon)}', '${escapeSql(row.lunIljin)}', ${nullableNum(row.solJd || row.julianDay)}, ${weekday}, 'kasi-calendar-api', '${escapeSql(`${fromYear}-${toYear}`)}')
ON CONFLICT (date) DO UPDATE SET
  lunar_year = EXCLUDED.lunar_year,
  lunar_month = EXCLUDED.lunar_month,
  lunar_day = EXCLUDED.lunar_day,
  is_leap_month = EXCLUDED.is_leap_month,
  year_ganji = EXCLUDED.year_ganji,
  month_ganji = EXCLUDED.month_ganji,
  day_ganji = EXCLUDED.day_ganji,
  julian_day = EXCLUDED.julian_day,
  weekday = EXCLUDED.weekday,
  source_id = EXCLUDED.source_id,
  source_version = EXCLUDED.source_version,
  updated_at = now();`;
}

function solarTermSql(row, year) {
  const dateText = String(row.locdate || row.solLocdate || row.locDate || "");
  const date = `${dateText.slice(0, 4)}-${dateText.slice(4, 6)}-${dateText.slice(6, 8)}`;
  const timeText = String(row.kst || row.sunLongitudeTime || "00:00").replace(/[^0-9]/g, "").padStart(4, "0");
  const time = `${timeText.slice(0, 2)}:${timeText.slice(2, 4)}:00+09`;
  const name = row.dateName || row.termsName || row.name || "절기";
  const order = solarTermOrder(name);

  return `
INSERT INTO solar_terms
  (year, name, occurred_at, term_order, source_id, source_version)
VALUES
  (${year}, '${escapeSql(name)}', '${date} ${time}', ${order}, 'kasi-calendar-api', '${escapeSql(`${fromYear}-${toYear}`)}')
ON CONFLICT (year, name) DO UPDATE SET
  occurred_at = EXCLUDED.occurred_at,
  term_order = EXCLUDED.term_order,
  source_id = EXCLUDED.source_id,
  source_version = EXCLUDED.source_version,
  updated_at = now();`;
}

function solarTermOrder(name) {
  const terms = [
    "소한", "대한", "입춘", "우수", "경칩", "춘분", "청명", "곡우",
    "입하", "소만", "망종", "하지", "소서", "대서", "입추", "처서",
    "백로", "추분", "한로", "상강", "입동", "소설", "대설", "동지",
  ];
  const index = terms.indexOf(name);
  return index >= 0 ? index + 1 : 0;
}

function parseArgs(argv) {
  const result = {};
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i].startsWith("--")) {
      result[argv[i].slice(2)] = argv[i + 1];
      i += 1;
    }
  }
  return result;
}

async function readServiceKey() {
  let key;
  if (args["key-file"]) {
    const raw = await fs.readFile(args["key-file"], "utf8");
    key = raw.trim();
  } else {
    key = process.env.DATA_GO_KR_SERVICE_KEY;
  }

  if (key && key.includes("%")) {
    try {
      return decodeURIComponent(key);
    } catch {
      return key;
    }
  }

  return key;
}

function redactServiceKey(url) {
  const safeUrl = new URL(url);
  if (safeUrl.searchParams.has("ServiceKey")) {
    safeUrl.searchParams.set("ServiceKey", "REDACTED");
  }
  if (safeUrl.searchParams.has("serviceKey")) {
    safeUrl.searchParams.set("serviceKey", "REDACTED");
  }
  return safeUrl.toString();
}

function pad(value) {
  return String(value).padStart(2, "0");
}

function num(value) {
  return Number.parseInt(value, 10);
}

function nullableNum(value) {
  const parsed = Number.parseFloat(value);
  return Number.isFinite(parsed) ? parsed : "NULL";
}

function weekdayNumber(date) {
  return new Date(`${date}T00:00:00+09:00`).getDay();
}

function escapeSql(value) {
  return String(value ?? "").replaceAll("'", "''");
}

function decodeXml(value) {
  return String(value ?? "")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&amp;", "&")
    .replaceAll("&quot;", '"')
    .replaceAll("&apos;", "'");
}
